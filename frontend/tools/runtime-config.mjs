import { randomUUID } from "node:crypto";
import { mkdir, open, readFile, rename, unlink } from "node:fs/promises";
import path from "node:path";

const FRONTEND_RUNTIME_CONFIG_PATH = path.join("frontend", "public", "config.js");
const FRONTEND_RUNTIME_CONFIG_MARKER = "// Generated by Dotcore development environment.\n";
const DEFAULT_FILE_SYSTEM = { mkdir, open, readFile, rename, unlink };

export function frontendRuntimeConfigPath(root = process.cwd(), targetPath) {
  const resolvedRoot = path.resolve(root);
  return targetPath === undefined
    ? path.join(resolvedRoot, FRONTEND_RUNTIME_CONFIG_PATH)
    : path.resolve(resolvedRoot, targetPath);
}

export function serializeFrontendRuntimeConfig(environment) {
  const config = {
    managementOrigin: validateFrontendOrigin(
      environment.VITE_DOTCORE_MANAGEMENT_ORIGIN ?? environment.DOTCORE_MANAGEMENT_ORIGIN,
      "VITE_DOTCORE_MANAGEMENT_ORIGIN",
    ),
    inferenceOrigin: validateFrontendOrigin(
      environment.VITE_DOTCORE_INFERENCE_ORIGIN ?? environment.DOTCORE_INFERENCE_ORIGIN,
      "VITE_DOTCORE_INFERENCE_ORIGIN",
    ),
  };
  return `${FRONTEND_RUNTIME_CONFIG_MARKER}window.__DOTCORE_CONFIG__ = ${JSON.stringify(config)};\n`;
}

export async function generateFrontendRuntimeConfig(
  root = process.cwd(),
  environment = process.env,
  { fileSystem = DEFAULT_FILE_SYSTEM, targetPath } = {},
) {
  const configPath = frontendRuntimeConfigPath(root, targetPath);
  const configContents = serializeFrontendRuntimeConfig(environment);
  await fileSystem.mkdir(path.dirname(configPath), { recursive: true });

  try {
    const existingContents = await fileSystem.readFile(configPath, "utf8");
    if (!existingContents.startsWith(FRONTEND_RUNTIME_CONFIG_MARKER)) {
      throw new Error(
        `Refusing to replace existing frontend runtime config '${configPath}' because it was not generated by the development environment.`,
      );
    }
  } catch (error) {
    if (error.code !== "ENOENT") {
      throw error;
    }
  }

  const temporaryPath = path.join(
    path.dirname(configPath),
    `.${path.basename(configPath)}.${randomUUID()}.tmp`,
  );
  let handle;
  try {
    handle = await fileSystem.open(temporaryPath, "wx", 0o600);
    await handle.writeFile(configContents);
    await handle.sync();
    await handle.close();
    handle = undefined;
    await fileSystem.rename(temporaryPath, configPath);
  } catch (error) {
    throw diagnostic(`Cannot atomically generate frontend runtime config '${configPath}'`, error);
  } finally {
    try {
      await handle?.close();
    } catch (error) {
      throw diagnostic(`Cannot close generated frontend runtime config '${temporaryPath}'`, error);
    }
    try {
      await fileSystem.unlink(temporaryPath);
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw diagnostic(
          `Cannot clean generated frontend runtime config '${temporaryPath}'`,
          error,
        );
      }
    }
  }

  return { configPath, generated: true };
}

function validateFrontendOrigin(value, variable) {
  if (value === "same-origin") {
    return value;
  }

  if (typeof value !== "string" || !value.trim()) {
    throw new Error(`${variable} must be a valid HTTP(S) origin.`);
  }

  let origin;
  try {
    origin = new URL(value);
  } catch {
    throw new Error(`${variable} must be a valid HTTP(S) origin.`);
  }

  if (
    (origin.protocol !== "http:" && origin.protocol !== "https:") ||
    !origin.hostname ||
    origin.username ||
    origin.password ||
    origin.pathname !== "/" ||
    origin.search ||
    origin.hash
  ) {
    throw new Error(`${variable} must be a valid HTTP(S) origin.`);
  }

  return origin.origin;
}

function diagnostic(message, cause) {
  return new Error(cause ? `${message}: ${cause.message}` : message);
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const [root = process.cwd(), targetPath] = process.argv.slice(2);
  generateFrontendRuntimeConfig(root, process.env, { targetPath })
    .then(({ configPath }) =>
      process.stdout.write(`Dotcore frontend runtime config: ${configPath}\n`),
    )
    .catch((error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    });
}

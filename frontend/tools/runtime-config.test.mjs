import assert from "node:assert/strict";
import {
  chmod,
  mkdir,
  mkdtemp,
  open,
  readFile,
  rename,
  rm,
  unlink,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import test from "node:test";

import {
  frontendRuntimeConfigPath,
  generateFrontendRuntimeConfig,
  serializeFrontendRuntimeConfig,
} from "./runtime-config.mjs";

const environment = {
  VITE_DOTCORE_MANAGEMENT_ORIGIN: "https://backend.example:6207/",
  VITE_DOTCORE_INFERENCE_ORIGIN: "http://inference.example:6407/",
};
const expectedConfig =
  '// Generated by Dotcore development environment.\nwindow.__DOTCORE_CONFIG__ = {"managementOrigin":"https://backend.example:6207","inferenceOrigin":"http://inference.example:6407"};\n';

async function fixture(t) {
  const root = await mkdtemp(path.join(tmpdir(), "dotcore-runtime-config-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  return root;
}

test("serializes the exact runtime-config bytes and normalizes HTTP(S) origins", () => {
  assert.equal(serializeFrontendRuntimeConfig(environment), expectedConfig);
  assert.equal(
    serializeFrontendRuntimeConfig({
      VITE_DOTCORE_MANAGEMENT_ORIGIN: "same-origin",
      VITE_DOTCORE_INFERENCE_ORIGIN: "same-origin",
    }),
    '// Generated by Dotcore development environment.\nwindow.__DOTCORE_CONFIG__ = {"managementOrigin":"same-origin","inferenceOrigin":"same-origin"};\n',
  );
  assert.equal(
    serializeFrontendRuntimeConfig({
      DOTCORE_MANAGEMENT_ORIGIN: "http://backend.example:6207",
      DOTCORE_INFERENCE_ORIGIN: "http://inference.example:6407/",
    }),
    expectedConfig.replace("https://backend.example:6207", "http://backend.example:6207"),
  );
});

test("rejects origins that are not bare HTTP(S) origins", () => {
  for (const [variable, value] of [
    ["VITE_DOTCORE_MANAGEMENT_ORIGIN", ""],
    ["VITE_DOTCORE_MANAGEMENT_ORIGIN", "ftp://backend.example"],
    ["VITE_DOTCORE_MANAGEMENT_ORIGIN", "https://user:secret@backend.example"], // trufflehog:ignore
    ["VITE_DOTCORE_MANAGEMENT_ORIGIN", "https://backend.example/api"],
    ["VITE_DOTCORE_INFERENCE_ORIGIN", "http://inference.example?debug=1"],
    ["VITE_DOTCORE_INFERENCE_ORIGIN", "not-an-url"],
    ["VITE_DOTCORE_MANAGEMENT_ORIGIN", "same-origin/"],
    ["VITE_DOTCORE_INFERENCE_ORIGIN", "SAME-ORIGIN"],
  ]) {
    const values = { ...environment, [variable]: value };
    assert.throws(
      () => serializeFrontendRuntimeConfig(values),
      new RegExp(`${variable} must be a valid HTTP\\(S\\) origin`, "i"),
    );
  }
});

test("resolves a selected serving root and retains generated output", async (t) => {
  const root = await fixture(t);
  const servingRoot = path.join(root, "stage", "static");
  const configPath = path.join(servingRoot, "config.js");

  assert.equal(
    frontendRuntimeConfigPath(root, path.join("stage", "static", "config.js")),
    configPath,
  );
  await generateFrontendRuntimeConfig(root, environment, { targetPath: configPath });
  assert.equal(await readFile(configPath, "utf8"), expectedConfig);
  assert.equal(await readFile(configPath, "utf8"), expectedConfig);
});

test("replaces an owned file through rename without exposing partial bytes", async (t) => {
  const root = await fixture(t);
  const configPath = path.join(root, "static", "config.js");
  await generateFrontendRuntimeConfig(root, environment, { targetPath: configPath });
  let destinationAtRename;
  const realReadFile = readFile;
  await generateFrontendRuntimeConfig(
    root,
    {
      ...environment,
      VITE_DOTCORE_MANAGEMENT_ORIGIN: "http://replacement.example:6207",
    },
    {
      targetPath: configPath,
      fileSystem: {
        mkdir,
        readFile: (...args) => realReadFile(...args),
        open,
        rename: async (temporaryPath, destinationPath) => {
          destinationAtRename = await realReadFile(destinationPath, "utf8");
          return rename(temporaryPath, destinationPath);
        },
        unlink,
      },
    },
  );
  assert.equal(destinationAtRename, expectedConfig);
  assert.match(await readFile(configPath, "utf8"), /replacement\.example/);
});

test("refuses to replace an unowned config.js", async (t) => {
  const root = await fixture(t);
  const configPath = path.join(root, "static", "config.js");
  const unowned = "window.__DOTCORE_CONFIG__ = {};\n";
  await mkdir(path.dirname(configPath), { recursive: true });
  await writeFile(configPath, unowned);
  await assert.rejects(
    generateFrontendRuntimeConfig(root, environment, { targetPath: configPath }),
    /Refusing to replace existing frontend runtime config/i,
  );
  assert.equal(await readFile(configPath, "utf8"), unowned);
});

test("frontend startup generates before serving and does not serve after generation failure", async (t) => {
  const root = await fixture(t);
  const bin = path.join(root, "bin");
  const generated = path.join(root, "generated");
  const started = path.join(root, "started");
  await mkdir(bin, { recursive: true });
  await writeFile(
    path.join(bin, "node"),
    `#!/bin/sh
case "$*" in *runtime-config.mjs*) touch "${generated}"; exit "\${NODE_CONFIG_STATUS:-0}";; esac
exit 19
`,
  );
  await writeFile(
    path.join(bin, "npm"),
    `#!/bin/sh
[ -f "${generated}" ] || exit 23
touch "${started}"
`,
  );
  await Promise.all([chmod(path.join(bin, "node"), 0o755), chmod(path.join(bin, "npm"), 0o755)]);
  const repositoryRoot = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "..");
  const result = spawnSync("just", ["frontend", "run-dev"], {
    cwd: repositoryRoot,
    encoding: "utf8",
    env: { ...process.env, JUST_TEMPDIR: root, PATH: `${bin}:${process.env.PATH}` },
  });
  assert.equal(result.status, 0, result.stderr);
  assert.equal(await readFile(started, "utf8"), "");

  const failed = spawnSync("just", ["frontend", "run-dev"], {
    cwd: repositoryRoot,
    encoding: "utf8",
    env: {
      ...process.env,
      JUST_TEMPDIR: root,
      NODE_CONFIG_STATUS: "17",
      PATH: `${bin}:${process.env.PATH}`,
    },
  });
  assert.equal(failed.status, 17, failed.stderr);
});

test("Nix startup serves only after runtime-config generation", async (t) => {
  const root = await fixture(t);
  const bin = path.join(root, "bin");
  const artifact = path.join(root, "artifact");
  const serverArtifact = path.join(root, "server-artifact");
  const generated = path.join(root, "generated");
  const started = path.join(root, "started");
  await mkdir(path.join(artifact, "assets"), { recursive: true });
  await mkdir(path.join(serverArtifact, "bin"), { recursive: true });
  await mkdir(bin, { recursive: true });
  await writeFile(path.join(artifact, "index.html"), "index\n");
  await writeFile(
    path.join(serverArtifact, "bin", "dotcore-frontend-server"),
    `#!/bin/sh
[ -f "${generated}" ] || exit 23
touch "${started}"
`,
  );
  await writeFile(
    path.join(bin, "node"),
    `#!/bin/sh
case "$*" in *runtime-config.mjs*) touch "${generated}"; exit "\${NODE_CONFIG_STATUS:-0}";; esac
exit 19
`,
  );
  await writeFile(
    path.join(bin, "nix"),
    `#!/bin/sh
case "$1 $2" in
  "build .#frontend") printf '%s\\n' "${artifact}" ;;
  "build .#frontend-server") ln -s "${serverArtifact}" "$4" ;;
  *) exit 19 ;;
esac
`,
  );
  await chmod(path.join(serverArtifact, "bin", "dotcore-frontend-server"), 0o755);
  await Promise.all([chmod(path.join(bin, "node"), 0o755), chmod(path.join(bin, "nix"), 0o755)]);
  const repositoryRoot = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "..");
  const result = spawnSync("just", ["frontend", "run-nix"], {
    cwd: repositoryRoot,
    encoding: "utf8",
    env: {
      ...process.env,
      DOTCORE_MACHINE_HOST: "127.0.0.1",
      DOTCORE_FRONTEND_PORT: "6207",
      JUST_TEMPDIR: root,
      PATH: `${bin}:${process.env.PATH}`,
    },
  });
  assert.equal(result.status, 0, result.stderr);
  assert.equal(await readFile(started, "utf8"), "");
});
